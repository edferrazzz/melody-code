#!/usr/bin/env python3
"""Builds the sample kits in Assets/Samples from the free source libraries (see Assets/Samples/LICENSES.txt).

usage: build_samples.py <source root> <repo root>
The source root holds the unpacked npm packages (tonejs-instrument-*, @audio-samples/piano-mp3-velocity*).
Every note is trimmed, faded, level matched and stored as mono Ogg Vorbis; bowed strings get a baked
crossfade loop so they can hold for a whole chord. Writes Source/SampleTable.inc as well.
"""
import os, re, subprocess, sys, tempfile, wave
import numpy as np

SR = 44100
NOTE = {'C': 0, 'D': 2, 'E': 4, 'F': 5, 'G': 7, 'A': 9, 'B': 11}

# name, folder, layer (velocity layer index), seconds kept, fade seconds, loop (start, end) seconds or None
INSTRUMENTS = [
    ('piano',  'pv6/package/audio',                     0, 7.0, 1.2, None),
    ('piano',  'pv12/package/audio',                    1, 7.0, 1.2, None),
    ('nylon',  'tonejs-instrument-guitar-nylon-mp3/package', 0, 5.0, 0.8, None),
    ('guitar', 'tonejs-instrument-guitar-acoustic-wav/package', 0, 6.0, 1.0, None),
    ('ebass',  'tonejs-instrument-bass-electric-wav/package', 0, 5.0, 0.8, None),
    ('harp',   'tonejs-instrument-harp-wav/package',    0, 5.0, 1.0, None),
    ('violin', 'tonejs-instrument-violin-wav/package',  0, 6.0, 0.0, (1.2, 5.6)),
    ('cello',  'tonejs-instrument-cello-wav/package',   0, 0.0, 0.0, (0.9, -0.5)),
]

def midi_of(name):
    m = re.fullmatch(r'([A-G])(s|#)?(-?\d)(v\d+)?', name)
    if not m: return None
    return (int(m.group(3)) + 1) * 12 + NOTE[m.group(1)] + (1 if m.group(2) else 0)

def decode(path):
    raw = subprocess.run(['ffmpeg', '-v', 'error', '-i', path, '-ac', '1', '-ar', str(SR), '-f', 'f32le', '-'],
                         check=True, capture_output=True).stdout
    return np.frombuffer(raw, dtype=np.float32).copy()

def prepare(x, keep, fade, loop):
    # start at the attack: skip leading silence
    above = np.nonzero(np.abs(x) > 0.004)[0]
    x = x[max(0, above[0] - 32):] if len(above) else x
    loopStart = loopEnd = 0
    if loop:
        ls = int(loop[0] * SR)
        le = int((loop[1] if loop[1] > 0 else len(x) / SR + loop[1]) * SR)
        le = min(le, len(x))
        xf = int(0.18 * SR)
        if le - ls > 2 * xf:
            f = np.linspace(0, 1, xf, dtype=np.float32)
            x = x[:le].copy()
            x[le - xf:le] = x[le - xf:le] * (1 - f) + x[ls - xf:ls] * f   # at le the sound continues as at ls
            loopStart, loopEnd = ls, le
    else:
        x = x[:int(keep * SR)].copy()
        n = int(fade * SR)
        if n and len(x) > n: x[-n:] *= np.linspace(1, 0, n, dtype=np.float32) ** 2
    # level: the body (first 400 ms after the attack) to -16 dBFS RMS, peak at most -1 dBFS
    body = x[:int(0.4 * SR)]
    rms = float(np.sqrt(np.mean(body ** 2)) + 1e-9)
    g = min(10 ** (-16 / 20) / rms, 0.89 / (float(np.max(np.abs(x))) + 1e-9))
    return (x * g).astype(np.float32), loopStart, loopEnd

def encode(x, out):
    with tempfile.NamedTemporaryFile(suffix='.wav') as t:
        with wave.open(t.name, 'wb') as w:
            w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR)
            w.writeframes((np.clip(x, -1, 1) * 32767).astype('<i2').tobytes())
        subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', t.name, '-c:a', 'libvorbis', '-q:a', '4', out], check=True)

def main(src, repo):
    outDir = os.path.join(repo, 'Assets', 'Samples')
    os.makedirs(outDir, exist_ok=True)
    rows = []
    for name, folder, layer, keep, fade, loop in INSTRUMENTS:
        d = os.path.join(src, folder)
        for f in sorted(os.listdir(d)):
            stem, ext = os.path.splitext(f)
            if ext not in ('.wav', '.mp3') or ' ' in stem: continue
            m = midi_of(stem)
            if m is None: continue
            x, ls, le = prepare(decode(os.path.join(d, f)), keep, fade, loop)
            file = f'{name}_{m}_{layer}.ogg'
            encode(x, os.path.join(outDir, file))
            rows.append((name, m, layer, ls, le, file.replace('.', '_')))
    with open(os.path.join(repo, 'Source', 'SampleTable.inc'), 'w') as t:
        t.write('// generated by tools/build_samples.py: instrument, root note, velocity layer, loop start, loop end, resource\n')
        for r in rows: t.write('{ "%s", %d, %d, %d, %d, "%s" },\n' % r)
    print(len(rows), 'samples')

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
